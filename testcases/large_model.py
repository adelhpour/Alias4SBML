# calculate the reduction in the total curve length

net = sbmlnetwork.load("original_model.xml")
curves = net.get_reactions_list().get_curves_list()
original_model_total_curve_length = 0
for curve in curves:
    start = curve.get_start()
    end = curve.get_end()
    original_model_total_curve_length += math.sqrt((end[0] - start[0]) ** 2 + (end[1] - start[1]) ** 2)

net = sbmlnetwork.load("aliased_model.xml")
curves = net.get_reactions_list().get_curves_list()
aliased_model_total_curve_length = 0
for curve in curves:
    start = curve.get_start()
    end = curve.get_end()
    aliased_model_total_curve_length += math.sqrt((end[0] - start[0]) ** 2 + (end[1] - start[1]) ** 2)

reduction = (original_model_total_curve_length - aliased_model_total_curve_length) / original_model_total_curve_length * 100
print(reduction)

